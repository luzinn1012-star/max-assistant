"""Injectable adapter contracts; imports never initialize Windows APIs."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol

if TYPE_CHECKING:
    from skills.apps import AppSpec


class WindowsAdapter(Protocol):
    def windows(self, spec: AppSpec) -> list[dict[str, Any]]: ...
    def focus(self, window: dict[str, Any]) -> bool: ...
    def launch(self, spec: AppSpec) -> str: ...
    def observe_launch(self, spec: AppSpec) -> dict[str, Any]: ...
    def prepare_close(self, spec: AppSpec) -> list[dict[str, Any]]: ...
    def request_close(self, spec: AppSpec, windows: list[dict[str, Any]]) -> int: ...
    def known_folder(self, folder: str) -> Path: ...
    def open_path(self, path: Path) -> None: ...
    def system_status(self) -> dict[str, Any]: ...


class AudioDevice(Protocol):
    def __enter__(self) -> AudioDevice: ...
    def __exit__(self, *args: Any) -> bool | None: ...
    def state(self) -> dict[str, Any]: ...
    def set_volume(self, value: float) -> None: ...
    def set_mute(self, muted: bool) -> None: ...


AudioFactory = Callable[[], AudioDevice]
